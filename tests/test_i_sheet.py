"""QA section I. Evidence sheet and letter."""

from datetime import datetime

from tests.htmltool import find_all, html_text, one, parse, raw_html

ROOM_1_LETTER = """Dear [recipient],

We are students who use Demo Estate Study Room. From 2026-09-14 to 2026-09-16, we recorded 6 temperature and humidity readings in this room.

The highest humidex was 47.6 (Dangerous) on 2026-09-16 15:00, when the air temperature was 34 °C and the relative humidity was 65 %. Humidity added 13.6 humidex points on top of the air temperature.

Readings by humidex comfort band: Dangerous 2, Great discomfort 4.

Could you please check the ventilation, fans or air-conditioning in this room? We can share the full list of readings.

Thank you,
[your name]"""


def _letter(html):
    area = one(parse(html), "textarea", attrs={"id": "letter"})
    raw = area.raw_text().replace("\r\n", "\n").replace("\r", "\n")
    return raw.strip()


def test_74_sheet(client):
    response = client.get("/rooms/1/sheet")
    assert response.status_code == 200
    html = raw_html(response)
    root = parse(html)
    assert one(root, "h1").text() == "Heat evidence sheet: Demo Estate Study Room"
    assert find_all(root, cls="banner-sample")
    summary = one(root, "ul", attrs={"id": "summary"}).text()
    for piece in (
        "Room: Demo Estate Study Room",
        "Period: 2026-09-14 to 2026-09-16",
        "Readings: 6",
        "Highest: 47.6 (Dangerous) on 2026-09-16 15:00",
        "Latest: 47.6 (Dangerous) on 2026-09-16 15:00",
        "Great discomfort or above: 6 of 6",
    ):
        assert piece in summary
    chart = one(root, "svg", cls="chart")
    assert len(find_all(chart, "circle", cls="point")) == 6
    rows = [
        row
        for row in find_all(one(root, "table", attrs={"id": "readings"}), "tr")
        if row.attrs.get("data-reading-id")
    ]
    assert len(rows) == 6
    assert "<form" not in html.lower()


def test_75_letter_exact(client):
    html = raw_html(client.get("/rooms/1/sheet"))
    assert _letter(html) == ROOM_1_LETTER.strip()


def test_76_sheet_parts(client):
    response = client.get("/rooms/1/sheet")
    html = raw_html(response)
    root = parse(html)
    printed = one(root, attrs={"id": "letter-print"}).text()
    assert "We are students who use Demo Estate Study Room." in printed
    assert "Readings by humidex comfort band: Dangerous 2, Great discomfort 4." in printed
    copy = one(root, "button", attrs={"id": "copy-letter"})
    print_button = one(root, "button", attrs={"id": "print-sheet"})
    assert copy.attrs.get("type") == "button"
    assert print_button.attrs.get("type") == "button"
    assert "mailto:" not in html
    text = html_text(response)
    today = datetime.now().strftime("%Y-%m-%d")
    assert "Hot Room Log does not send anything." in text
    assert f"Generated by Hot Room Log on {today}" in text
    for token in ("6.105", "17.27", "237.7", "0.5555"):
        assert token in text


